# --------------------------------------------------------------------- 基础转换


def _布尔(值: Any, 默认: bool) -> bool:
    if isinstance(值, bool):
        return 值
    if isinstance(值, (int, float)):
        return 值 != 0
    if isinstance(值, str):
        s = 值.strip().lower()
        if s in ("1", "true", "on", "yes", "y", "是", "开", "开启", "启用"):
            return True
        if s in ("0", "false", "off", "no", "n", "否", "关", "关闭", "禁用", ""):
            return False
    return 默认


def _浮点(值: Any, 默认: float, 最小: float | None = None, 最大: float | None = None) -> float:
    try:
        if isinstance(值, str):
            值 = 值.strip().rstrip("秒sS分mM")
        f = float(值)
    except (TypeError, ValueError):
        return 默认
    if f != f or f in (float("inf"), float("-inf")):
        return 默认
    if 最小 is not None and f < 最小:
        f = 最小
    if 最大 is not None and f > 最大:
        f = 最大
    return round(f, 3)


def _整数(值: Any, 默认: int, 最小: int | None = None, 最大: int | None = None) -> int:
    try:
        i = int(float(str(值).strip()))
    except (TypeError, ValueError):
        return 默认
    if 最小 is not None and i < 最小:
        i = 最小
    if 最大 is not None and i > 最大:
        i = 最大
    return i


def _字符串(值: Any, 默认: str) -> str:
    if isinstance(值, str):
        return 值.strip()
    if 值 is None:
        return 默认
    return str(值).strip()


def _字符串列表(值: Any) -> list[str]:
    """接受 list/tuple/set/字符串（换行或逗号分隔），去空去重保序。"""
    if 值 is None:
        return []
    if isinstance(值, str):
        原 = 值.replace("，", ",").replace("\r", "\n").replace("\n", ",").split(",")
    elif isinstance(值, (list, tuple, set)):
        原 = list(值)
    else:
        原 = [值]
    结果: list[str] = []
    for 项 in 原:
        if isinstance(项, str):
            s = 项.strip()
        elif 项 is None:
            continue
        else:
            s = str(项).strip()
        if s and s not in 结果:
            结果.append(s)
    return 结果


def _枚举(值: Any, 可选: tuple[str, ...], 默认: str) -> str:
    s = _字符串(值, 默认)
    return s if s in 可选 else 默认


def _枚举列表(值: Any, 可选: tuple[str, ...]) -> list[str]:
    return [i for i in _字符串列表(值) if i in 可选]


# --------------------------------------------------------------------- 条件


def 规范化条件(原始: Any) -> dict[str, Any]:
    原始 = 原始 if isinstance(原始, dict) else {}
    类型 = _字符串(原始.get("类型"), "艾特唤醒")
    if 类型 not in 条件类型:
        类型 = "艾特唤醒"
    后 = copy.deepcopy(默认条件)
    后["id"] = _字符串(原始.get("id"), "") or f"c{uuid.uuid4().hex[:10]}"
    后["类型"] = 类型
    后["开关"] = _布尔(原始.get("开关"), True)
    后["提示词"] = _字符串(原始.get("提示词"), "")
    后["提示词临时"] = _布尔(原始.get("提示词临时"), True)
    后["正则"] = _字符串列表(原始.get("正则"))
    后["概率"] = _浮点(原始.get("概率"), 0.0, 0.0, 1.0)
    后["概率方式"] = _枚举列表(原始.get("概率方式"), 概率方式可选) or list(默认条件["概率方式"])
    # 分钟，0 = 不冷却
    后["概率冷却"] = _浮点(原始.get("概率冷却"), 0.0, 0.0, 10080.0)
    return 后


def _按旧优先级排序(列表: Any) -> list[dict[str, Any]]:
    """v2 -> v3：把数字优先级翻译成数组顺序（大的在前）。"""
    有效 = [i for i in (列表 or []) if isinstance(i, dict)]
    标 = sorted(enumerate(有效), key=lambda 项: (-_整数(项[1].get("优先级"), 0), 项[0]))
    return [项 for _, 项 in 标]


def _从v1转换(原始: dict[str, Any]) -> list[dict[str, Any]]:
    """把 v1 的固定开关翻译成条件流水线，保留原有语义顺序。"""
    条件: list[dict[str, Any]] = []

    def 加(类型: str, **参数: Any) -> None:
        条件.append({"类型": 类型, **参数})

    if _布尔(原始.get("艾特唤醒"), True):
        加("艾特唤醒")
    if _布尔(原始.get("引用唤醒"), True):
        加("引用唤醒")
    if _布尔(原始.get("无艾特引用唤醒"), False):
        加("无艾特引用唤醒")
    if _字符串列表(原始.get("唤醒正则")):
        加("唤醒正则", 正则=_字符串列表(原始.get("唤醒正则")))
    if _字符串列表(原始.get("拦截正则")):
        加("屏蔽正则", 正则=_字符串列表(原始.get("拦截正则")))
    if _布尔(原始.get("拦截JSON"), False):
        加("屏蔽卡片")
    if _布尔(原始.get("拦截戳一戳"), False):
        加("屏蔽戳一戳")
    if _布尔(原始.get("其余拦截"), False):
        加("其余屏蔽")
    概率 = _浮点(原始.get("概率唤醒"), 0.0, 0.0, 1.0)
    if 概率 > 0:
        加("概率唤醒", 概率=概率, 概率方式=_字符串列表(原始.get("概率方式")))

    return [规范化条件(c) for c in 条件]


def _换名(原始: dict[str, Any], 新: str, 旧: str) -> Any:
    """读取重命名后的字段，兼容旧键。"""
    值 = 原始.get(新)
    if 值 in (None, [], ""):
        值 = 原始.get(旧)
    return 值


def _迁移条件项(原始: dict[str, Any], 阶段: str) -> dict[str, Any]:
    """v1.4.0 的「屏蔽无艾特引用」并入「无艾特引用唤醒」。

    两个流水线里含义不同，所以开关要换算：

    - 接收流水线：原来「屏蔽」= 现在这条唤醒「关闭」（关闭即屏蔽）
    - LLM 前流水线：原来「屏蔽」= 现在这条唤醒「开启」（开启即拦截）
    """
    if 原始.get("类型") != "屏蔽无艾特引用":
        return 原始
    新 = dict(原始)
    新["类型"] = "无艾特引用唤醒"
    if 阶段 == "接收":
        新["开关"] = not _布尔(原始.get("开关"), True)
    return 新


def _规范化LLM条件(原始: Any, 已用ID: set[str]) -> list[dict[str, Any]]:
    """LLM 请求前流水线：只保留屏蔽类条件，并避免 id 与接收流水线撞车。"""
    结果: list[dict[str, Any]] = []
    if not isinstance(原始, (list, tuple)):
        return 结果
    for 项 in 原始:
        if not isinstance(项, dict):
            continue
        条件 = 规范化条件(_迁移条件项(项, "LLM"))
        if 条件["类型"] not in LLM前条件类型:
            continue
        if 条件["id"] in 已用ID:
            条件["id"] = f"c{uuid.uuid4().hex[:10]}"
        已用ID.add(条件["id"])
        结果.append(条件)
    return 结果


# --------------------------------------------------------------------- 规则


def 规范化规则(原始: Any) -> dict[str, Any]:
    """把任意原始数据收敛为一条完整规则。"""
    原始 = 原始 if isinstance(原始, dict) else {}
    后 = copy.deepcopy(默认规则)

    if "条件" not in 原始 and any(
        键 in 原始 for 键 in ("艾特唤醒", "引用唤醒", "唤醒正则", "拦截正则", "其余拦截")
    ):
        条件 = _从v1转换(原始)
    else:
        条件 = [规范化条件(_迁移条件项(c, "接收")) for c in _按旧优先级排序(原始.get("条件"))]
        if not 条件:
            条件 = _默认条件列表()

    已用ID: set[str] = set()
    去重条件: list[dict[str, Any]] = []
    for 条件项 in 条件:
        if 条件项["id"] in 已用ID:
            条件项["id"] = f"c{uuid.uuid4().hex[:10]}"
        已用ID.add(条件项["id"])
        去重条件.append(条件项)
    后["条件"] = 去重条件

    # 旧版「屏蔽空消息链」是布尔设置，现在并入流水线：开过的规则补一条屏蔽条件，
    # 放在最前面，保持原来「先于一切判断」的语义
    if _布尔(原始.get("屏蔽空消息链"), False) and not any(
        c["类型"] == "屏蔽空消息链" for c in 去重条件
    ):
        补 = 规范化条件({"类型": "屏蔽空消息链"})
        已用ID.add(补["id"])
        后["条件"].insert(0, 补)

    # 第二条流水线：只接受「阶段」含 LLM 的条件（即屏蔽类），唤醒类会被丢弃
    后["LLM前条件"] = _规范化LLM条件(原始.get("LLM前条件"), 已用ID)

    后["id"] = _字符串(原始.get("id"), "") or uuid.uuid4().hex[:12]
    # 备注允许留空：复制出来的规则会清空备注，等用户补填；
    # 展示侧统一走 规则名称() 兜底成「未命名规则」
    后["备注"] = _字符串(原始.get("备注"), "")
    后["开关"] = _布尔(原始.get("开关"), 默认规则["开关"])
    后["群号"] = _字符串列表(原始.get("群号"))

    后["持续活跃"] = _浮点(原始.get("持续活跃"), 默认规则["持续活跃"], -1.0, 86400.0)
