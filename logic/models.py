def 规范化数据(原始: Any) -> dict[str, Any]:
    原始 = 原始 if isinstance(原始, dict) else {}

    规则列表: list[dict[str, Any]] = []
    已用ID: set[str] = {"fallback"}
    # v2 及更早的数据带数字优先级：先按它排序，再丢掉字段
    for 项 in _按旧优先级排序(原始.get("规则列表")):
        规则 = 规范化规则(项)
        if 规则["id"] in 已用ID:
            规则["id"] = uuid.uuid4().hex[:12]
        已用ID.add(规则["id"])
        规则列表.append(规则)

    return {
        "版本": 数据版本,
        "规则列表": 规则列表,
        "兜底规则": 规范化兜底(原始.get("兜底规则")),
        "全局": 规范化全局(原始.get("全局")),
        "群目录": 规范化群目录(原始.get("群目录")),
    }


