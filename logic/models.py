def 复制规则(源: Any, 备注: str = "") -> dict[str, Any]:
    """按一条已有规则复制出一条新规则。

    - 条件、设置、提示词全部照抄；
    - `群号` 与 `备注` 是每条规则各自专属的字段，复制后清空，由用户自己填。
      群号留空的规则不会进入「群号 -> 规则」索引，等于**存着但哪儿都不生效**；
    - 条件 id 重新生成，避免两条规则里的同名 id 互相干扰（移动/删除按 id 定位）。
    """
    源 = 源 if isinstance(源, dict) else {}
    原始 = copy.deepcopy(源)
    原始["id"] = uuid.uuid4().hex[:12]
    原始["备注"] = 备注
    原始["群号"] = []
    for 键 in ("条件", "LLM前条件"):
        条件列表 = 原始.get(键)
        if not isinstance(条件列表, list):
            continue
        for 条件 in 条件列表:
            if isinstance(条件, dict):
                条件["id"] = f"c{uuid.uuid4().hex[:10]}"

    源条件 = 原始.get("条件")
    副本 = 规范化规则(原始)
    # 规范化会把「空条件」补成默认的 艾特唤醒 / 引用唤醒；
    # 源规则本来就是空的话，副本也保持空，才算「复制得一模一样」
    if isinstance(源条件, list) and not 源条件:
        副本["条件"] = []
    副本["备注"] = _字符串(备注, "")
    副本["群号"] = []
    return 副本


def 字段类型(键: str) -> type | None:
    """按默认值推断字段类型，供指令修改配置时做类型转换。"""
    if 键 not in 默认规则:
        return None
    return type(默认规则[键])


