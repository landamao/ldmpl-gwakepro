"""数据模型：规则、两条条件流水线、默认值与规范化。

核心是**顺序即优先级**：

- 一条规则里的 `条件` 是一个数组，数组顺序就是判断顺序（从上到下）；
- 规则列表的顺序就是规则之间的优先级（越靠前越优先），同一群号被多条规则
  声明时，只有最靠前的那条生效。

因此数据里不再有 `优先级` 数字，改由面板上的 ↑↓ 调整顺序。

v4 起有两条流水线，分别对应两个时机：

- `条件`：**收到消息时**判定，既能唤醒也能屏蔽（屏蔽 = `stop_event()`，
  其他插件也收不到这条消息）；
- `LLM前条件`：**进入 LLM 前**判定，只放屏蔽类条件，命中只终止这一轮回复，
  不打断其他插件对消息的处理。

    {
      "类型": "概率唤醒",
      "开关": true,
      "提示词": "这是一次概率主动唤醒",
      "正则": [], "概率": 0.05, "概率方式": ["纯文本"],
      "概率冷却": 10        # 分钟：命中后 10 分钟内不再判断该概率条件
    }

「唤醒还是屏蔽先判」也完全由数组顺序表达：屏蔽正则放在艾特前面就是屏蔽优先。
"""

