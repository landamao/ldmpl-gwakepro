def 规范化兜底(原始: Any) -> dict[str, Any]:
    合并 = copy.deepcopy(默认兜底规则)
    if isinstance(原始, dict):
        if "条件" not in 原始 and any(
            键 in 原始 for 键 in ("艾特唤醒", "引用唤醒", "唤醒正则", "拦截正则", "其余拦截")
        ):
            # 旧版兜底规则：丢掉默认条件，让规范化时走 v1 迁移
            合并.pop("条件", None)
        合并.update(原始)
    后 = 规范化规则(合并)
    后.update(
        {
            "id": "fallback",
            "备注": "兜底规则",
            "群号": [通配群号],
            "内置": True,
        }
    )
    # 兜底规则下面没有更下层可继承：-1（继承兜底）对它没有意义，统一收敛到 0
    for 键 in 时间字段:
        后[键] = max(0.0, 后[键])
    return 后


def 规范化全局(原始: Any) -> dict[str, Any]:
    原始 = 原始 if isinstance(原始, dict) else {}
    后 = copy.deepcopy(默认全局)
    后["黑名单群聊"] = _字符串列表(原始.get("黑名单群聊"))
    后["额外指令"] = _字符串列表(原始.get("额外指令"))
    后["提示词注入"] = _布尔(原始.get("提示词注入"), 默认全局["提示词注入"])
    for 键 in ("主动唤醒提示词", "提及唤醒提示词", "引用唤醒提示词"):
        值 = _字符串(原始.get(键), "")
        后[键] = 值 if 值 else 默认全局[键]
        后[f"{键}临时"] = _布尔(原始.get(f"{键}临时"), True)
    return 后


def 规范化群目录(原始: Any) -> dict[str, dict[str, Any]]:
    结果: dict[str, dict[str, Any]] = {}
    if not isinstance(原始, dict):
        return 结果
    for 群号, 值 in 原始.items():
        群号 = str(群号).strip()
        if not 群号:
            continue
        值 = 值 if isinstance(值, dict) else {}
        名称 = _字符串(值.get("名称"), "")
        try:
            时间 = float(值.get("时间", 0) or 0)
        except (TypeError, ValueError):
            时间 = 0.0
        结果[群号] = {"名称": 名称, "时间": round(时间, 3)}
    return 结果


